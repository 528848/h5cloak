ALTER TABLE review_templates
  ADD COLUMN kind VARCHAR(16) NOT NULL DEFAULT 'html' AFTER description,
  ADD COLUMN status VARCHAR(16) NOT NULL DEFAULT 'enabled' AFTER kind,
  ADD COLUMN url VARCHAR(500) NOT NULL DEFAULT '' AFTER html,
  ADD COLUMN host_header VARCHAR(255) NOT NULL DEFAULT '' AFTER url,
  ADD COLUMN timeout_ms INT UNSIGNED NOT NULL DEFAULT 8000 AFTER host_header,
  ADD COLUMN entry VARCHAR(255) NOT NULL DEFAULT 'index.html' AFTER timeout_ms,
  ADD COLUMN spa_fallback TINYINT(1) NOT NULL DEFAULT 0 AFTER entry,
  ADD COLUMN active_version INT UNSIGNED NOT NULL DEFAULT 0 AFTER spa_fallback,
  ADD COLUMN updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) AFTER created_at;

CREATE TABLE review_template_files (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  template_id BIGINT UNSIGNED NOT NULL,
  version INT UNSIGNED NOT NULL,
  dir VARCHAR(500) NOT NULL,
  entry VARCHAR(255) NOT NULL DEFAULT 'index.html',
  bytes BIGINT UNSIGNED NOT NULL DEFAULT 0,
  file_count INT UNSIGNED NOT NULL DEFAULT 0,
  status VARCHAR(16) NOT NULL DEFAULT 'ready',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_tpl_files_ver (template_id, version),
  CONSTRAINT fk_tpl_files_template FOREIGN KEY (template_id) REFERENCES review_templates (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
