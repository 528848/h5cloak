<?php

return [
    /*
    |--------------------------------------------------------------------------
    | 斗篷流量入口主机（CNAME 记录值）
    |--------------------------------------------------------------------------
    | 商户域名应通过 CNAME 解析到此地址，流量才会进入斗篷判定服务。
    | 示例：cloak-entry.example.com（需指向实际部署 Laravel 入口的服务器）
    */
    'entry_host' => env('CLOAK_ENTRY_HOST', ''),

    /*
    |--------------------------------------------------------------------------
    | 斗篷流量入口 IP（A 记录备选，仅用于展示）
    |--------------------------------------------------------------------------
    | 多个 IP 用英文逗号分隔，未配置 CNAME 时可在后台展示。
    */
    'entry_ips' => array_values(array_filter(array_map(
        'trim',
        explode(',', (string) env('CLOAK_ENTRY_IPS', ''))
    ))),

    /*
    |--------------------------------------------------------------------------
    | 域名托管 Nameservers（可选）
    |--------------------------------------------------------------------------
    | 若采用整域托管模式，在此配置 NS 列表，多个用英文逗号分隔。
    | 配置后后台将展示「设置主机记录」引导，而非 CNAME 记录。
    */
    'entry_nameservers' => array_values(array_filter(array_map(
        'trim',
        explode(',', (string) env('CLOAK_ENTRY_NAMESERVERS', ''))
    ))),
];
